#!/usr/bin/env node
/**
 * Precompile the Nunjucks templates under cloudflare/templates/ into an
 * ES module (src/generated/templates.js). Workers forbid runtime code
 * generation (new Function), so templates MUST be precompiled at build time
 * and rendered with the slim runtime.
 *
 * Run: node scripts/build-templates.mjs   (also wired as `npm run build:templates`)
 */

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import nunjucks from "nunjucks";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const templatesDir = path.join(root, "templates");
const outDir = path.join(root, "src", "generated");
const outFile = path.join(outDir, "templates.js");

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const p = path.join(dir, entry);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (p.endsWith(".html")) yield p;
  }
}

// The custom filters/tests below must be known at compile time so the
// compiler emits filter calls instead of failing; keep in sync with
// src/lib/web/templates.ts.
const env = new nunjucks.Environment(null, { autoescape: true, trimBlocks: true, lstripBlocks: true });
for (const f of ["dt", "enumerate"]) env.addFilter(f, (x) => x);
for (const t of ["none"]) env.addTest?.(t, () => true);

const chunks = [
  "// GENERATED by scripts/build-templates.mjs — do not edit.",
  "/** @type {Record<string, {root: Function, dependencies?: unknown}>} */",
  "export const precompiled = {};",
];

let count = 0;
const errors = [];
for (const file of walk(templatesDir)) {
  const name = path.relative(templatesDir, file).split(path.sep).join("/");
  const src = readFileSync(file, "utf8");
  try {
    const compiled = nunjucks.precompileString(src, {
      name,
      env,
      wrapper: (templates) =>
        templates
          .map((t) => `precompiled[${JSON.stringify(t.name)}] = (function() {${t.template}})();`)
          .join("\n"),
    });
    chunks.push(compiled);
    count++;
  } catch (e) {
    errors.push(`${name}: ${e.message}`);
  }
}

if (errors.length) {
  console.error(`FAILED to compile ${errors.length} template(s):`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, `${chunks.join("\n")}\n`);
writeFileSync(
  path.join(outDir, "templates.d.ts"),
  `// GENERATED by scripts/build-templates.mjs — do not edit.
export declare const precompiled: Record<string, { root: CallableFunction; dependencies?: unknown }>;
`,
);
console.log(`precompiled ${count} template(s) -> ${path.relative(root, outFile)}`);
